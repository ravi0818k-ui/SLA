#!/usr/bin/env node
/**
 * Builds the ad landing pages listed in ad-pages.json (e.g. /parents-ads-4-tuition-vs-exam/), plus a copy at each
 * alias (the original /ads-N/ URLs) so ads that still point there keep working.
 *
 * GitHub Pages has no URL rewrites, so each path is a real folder holding a copy of its source page.
 * The copy is adjusted so it works one folder deep:
 *   - relative src/href/srcset/poster URLs get a "../" prefix (assets stay in the repo root),
 *   - <html data-root="../"> tells script.js where data.json and quotes.json live,
 *   - the design-switch guard is removed (an ad path always shows its own design),
 *   - robots = noindex, follow; canonical and og:url point at the ad path.
 *
 * Usage: npm run build:ads        (writes the folders)
 *        npm run build:ads -- --check   (exits 1 if any generated page is out of date)
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SKIP = /^(?:[a-z][a-z0-9+.-]*:|\/\/|\/|#|\{\{|\.\.\/)/i; // absolute, scheme, hash, template, already prefixed

function prefixUrl(url, prefix) {
    const u = url.trim();
    return !u || SKIP.test(u) ? url : prefix + u;
}

function buildPage(html, page, cfg) {
    const prefix = '../';
    const url = cfg.baseUrl.replace(/\/$/, '') + '/' + page.path + '/';
    let out = html;

    // 1. design-switch guard: keep only the "js" class marker (needed for reveal animations)
    out = out.replace(/[ \t]*<!--\s*Design switch[\s\S]*?-->\s*\n?/, '');
    out = out.replace(/<script>((?:(?!<\/script>)[\s\S])*?location\.replace\(other[\s\S]*?)<\/script>/, function (m, body) {
        return /className \+= ' js'/.test(body) ? "<script>document.documentElement.className += ' js';</script>" : '';
    });

    // 2. links to the landing page stay on this ad page (index.html#faq -> #faq, index.html -> ./),
    //    every other relative URL -> one folder up
    out = out.replace(/(\s(?:src|href|poster))=(["'])([^"']*)\2/gi, function (m, attr, q, val) {
        const landing = /^(?:index|index-classic)\.html(#.*)?$/.exec(val.trim());
        if (landing && /href/i.test(attr)) return attr + '=' + q + (landing[1] || './') + q;
        return attr + '=' + q + prefixUrl(val, prefix) + q;
    });
    out = out.replace(/(\ssrcset)=(["'])([^"']*)\2/gi, function (m, attr, q, val) {
        const parts = val.split(',').map(function (s) {
            const t = s.trim().split(/\s+/);
            t[0] = prefixUrl(t[0], prefix);
            return t.join(' ');
        });
        return attr + '=' + q + parts.join(', ') + q;
    });

    // 3. root marker for script.js fetches
    out = out.replace(/<html(\s|>)/i, '<html data-root="' + prefix + '" data-ad-page="' + page.path + '"$1');

    // 4. SEO: noindex, self canonical
    const robots = '<meta name="robots" content="noindex, follow">';
    if (/<meta\s+name="robots"[^>]*>/i.test(out)) out = out.replace(/<meta\s+name="robots"[^>]*>/i, robots);
    else out = out.replace(/(<meta\s+charset[^>]*>)/i, '$1\n    ' + robots);
    out = out.replace(/(<link\s+rel="canonical"\s+href=")[^"]*(")/i, '$1' + url + '$2');
    out = out.replace(/(<meta\s+property="og:url"\s+content=")[^"]*(")/i, '$1' + url + '$2');

    // 5. banner
    const banner = '<!-- GENERATED by scripts/build-ad-pages.js from ' + page.source + ' for ' + url +
        ' . Do not edit here: edit ' + page.source + ', then run `npm run build:ads`. -->\n';
    out = out.replace(/^(\s*<!DOCTYPE[^>]*>\s*\n?)/i, '$1' + banner);
    if (out.indexOf(banner) < 0) out = banner + out;
    return out;
}

function loadConfig() {
    return JSON.parse(fs.readFileSync(path.join(ROOT, 'ad-pages.json'), 'utf-8'));
}

function buildAll(opts) {
    opts = opts || {};
    const cfg = loadConfig();
    const stale = [];
    cfg.pages.forEach(function (page) {
        if (!/^[a-z0-9-]+$/.test(page.path)) throw new Error('Bad path in ad-pages.json: ' + page.path);
        const src = fs.readFileSync(path.join(ROOT, page.source), 'utf-8');
        const html = buildPage(src, page, cfg);
        // the main path plus any aliases (older URLs such as /ads-1/): identical copies, canonical = main path
        [page.path].concat(page.aliases || []).forEach(function (dir) {
            if (!/^[a-z0-9-]+$/.test(dir)) throw new Error('Bad alias in ad-pages.json: ' + dir);
            const file = path.join(ROOT, dir, 'index.html');
            const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf-8') : null;
            if (current !== html) {
                stale.push(dir);
                if (!opts.check) {
                    fs.mkdirSync(path.dirname(file), { recursive: true });
                    fs.writeFileSync(file, html, 'utf-8');
                }
            }
        });
    });
    return stale;
}

module.exports = { buildPage, buildAll, loadConfig, prefixUrl };

if (require.main === module) {
    const check = process.argv.indexOf('--check') >= 0;
    const stale = buildAll({ check: check });
    if (check) {
        if (stale.length) { console.error('Out of date: ' + stale.join(', ') + ' (run npm run build:ads)'); process.exit(1); }
        console.log('Ad pages are up to date.');
    } else {
        console.log(stale.length ? 'Wrote: ' + stale.map(function (p) { return p + '/index.html'; }).join(', ') : 'Ad pages already up to date.');
    }
}
